"""Per-video accent colour, chosen at runtime from what the video is about. Run from edit/.
project.json:
  "accent": {"color": "#RRGGBB", "why": "the main product's brand colour (Claude's orange)"}
Choose it while storyboarding: the brand colour of the product being taught (its logo or primary button), else a
colour that fits the subject. It is the ONE accent of the video: through-line object, key word, highlight band,
morphing shapes and floods. Keep it apart from the hero-caption colour (that one comes from the speaker's clothes).
Writes work/gfx/assets/accent.css (imported at the top of base.css) with:
  --clay      the accent as a fill
  --clayText  a darker shade of the same hue that reaches 4.5:1 contrast on white (accent text on white)
  --band      a very light tint for highlight bands
and work/accent.json for the storyboard and report. Without "accent" it keeps the house default (#D97757)."""
import json, os, colorsys
cfg = json.load(open('project.json')) if os.path.exists('project.json') else {}
acc = cfg.get('accent', {}); hexc = acc.get('color', '#D97757')
rgb = tuple(int(hexc[i:i + 2], 16) / 255 for i in (1, 3, 5))
def lum(c):
    f = lambda v: v / 12.92 if v <= 0.03928 else ((v + 0.055) / 1.055) ** 2.4
    r, g, b = map(f, c); return 0.2126 * r + 0.7152 * g + 0.0722 * b
contrast = lambda a, b: (max(lum(a), lum(b)) + 0.05) / (min(lum(a), lum(b)) + 0.05)
h, l, s = colorsys.rgb_to_hls(*rgb)
text = rgb
while contrast(text, (1, 1, 1)) < 4.5 and l > 0.05:             # darken the same hue until text reads on white
    l -= 0.01; text = colorsys.hls_to_rgb(h, l, s)
band = colorsys.hls_to_rgb(h, 0.95, min(1.0, s * 0.9 + 0.05))    # a whisper of the hue for highlight bands
to_hex = lambda c: '#%02X%02X%02X' % tuple(round(v * 255) for v in c)
out = dict(color=hexc.upper(), text=to_hex(text), band=to_hex(band), why=acc.get('why', 'house default'),
           fill_contrast_on_white=round(contrast(rgb, (1, 1, 1)), 2), text_contrast_on_white=round(contrast(text, (1, 1, 1)), 2))
os.makedirs('work/gfx/assets', exist_ok=True)
open('work/gfx/assets/accent.css', 'w').write(
    f"/* per-video accent ({out['why']}) - generated by accent.py */\n"
    f"html:root {{ --clay: {out['color']}; --clayText: {out['text']}; --band: {out['band']}; }}\n")
json.dump(out, open('work/accent.json', 'w'), indent=1)
print(f"accent {out['color']} (text {out['text']}, band {out['band']}) - {out['why']}")
if out['fill_contrast_on_white'] < 1.6:
    print('WARNING: this accent is very pale on the near-white ground; fills will barely show. Pick a stronger colour.')
